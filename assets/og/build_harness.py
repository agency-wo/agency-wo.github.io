sys.path.insert(0, os.path.join(ROOT, ".build"))
import chrome  # noqa: E402
import chrome_it  # noqa: E402
import chrome_sq  # noqa: E402

NL = chr(10)
HERE = os.path.dirname(os.path.abspath(__file__))

# (html lang, harness file, the chrome module the service line is read from).
# The filenames pair with og-image.png / og-image-it.png / og-image-sq.png,
# which is the same suffix rule i18n.PREFIX applies to a page.
