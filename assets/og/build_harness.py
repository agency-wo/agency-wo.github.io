"""Emit the 3 share-card harnesses, one per language.

The card is a page rather than a PNG somebody once exported, for the reason
og-harness.html's own comment gives: the old card could not be regenerated,
only recreated, and it drifted a whole rebrand behind the site. This script is
the same defence one level up. The English harness carried its service line as
typed text, so the day chrome.py renamed a service the card would have kept
selling the old one, in the one image every share shows.

DERIVED, NOT TYPED. The service line is that language's chrome FOOT_LABELS[0]
joined with middots: the same 5 words the footer of every page already uses,
read from the same module, so the card and the site cannot call a service two
different things. Nothing else on the card is a sentence, which is why this
file needs no key in chrome.py and no entry in any stamp table.

THREE STATIC FILES, not one harness with a query parameter. The harness loads
the site's own /css/tokens.css over http.server, and a ?lang= switch would
need a script in the page to rewrite the line, which is a moving part in a
file whose entire job is to hold still for a camera.

TO REGENERATE THE HARNESSES:  python assets/og/build_harness.py
TO REGENERATE THE 3 PNGs:
  python -m http.server 8099            # from the project root
  then screenshot, at exactly 1200x630 and deviceScaleFactor 1:
    /assets/og/og-harness.html     -> og-image.png
    /assets/og/og-harness-it.html  -> og-image-it.png
    /assets/og/og-harness-sq.html  -> og-image-sq.png
  Any headless browser will do. There is deliberately no node dependency here.
"""
