def write_if_changed(path, body):
    old = io.open(path, encoding="utf-8").read() if os.path.exists(path) else None
    if old == body:
        return "unchanged"
    io.open(path, "w", encoding="utf-8", newline=NL).write(body)
    return "written"


for lang, fn, mod in CARDS:
    line = "<b>&middot;</b>".join(mod.FOOT_LABELS[0])
    body = TEMPLATE.format(lang=lang, services=line,
                           mod_suffix="" if lang == "en" else "_" + lang)
    print(fn, write_if_changed(os.path.join(HERE, fn), body))
